def tr(lang: str, key: str, **fmt) -> str:
    """取指定语言的文案，缺失时回落到中文。"""
    table = STRINGS.get(lang) or STRINGS["zh"]
    text = table.get(key)
    if text is None:
        text = STRINGS["zh"].get(key, key)
    if fmt:
        try:
            return text.format(**fmt)
        except (KeyError, IndexError, ValueError):
            return text
    return text
